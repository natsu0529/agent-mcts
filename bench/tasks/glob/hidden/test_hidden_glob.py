import pytest
from globmatch import match

CASES = [
    # literals and whole-path matching
    ("a/b", "a/b", True),
    ("a/b", "a/b/c", False),
    ("a/b/c", "a/b", False),
    ("A", "a", False),
    ("", "", True),
    ("", "a", False),
    # star and question mark
    ("*", "abc", True),
    ("*", "a/b", False),
    ("a*c", "ac", True),
    ("a*c", "abbbc", True),
    ("a*c", "abd", False),
    ("*a*b*", "xaybz", True),
    ("?", "", False),
    ("a?c", "a/c", False),
    ("*.py", "x.pyc", False),
    ("*/*", "a/b", True),
    ("*/*", "a", False),
    # character classes
    ("[abc]x", "bx", True),
    ("[abc]x", "dx", False),
    ("[a-c]x", "bx", True),
    ("[!a-c]x", "bx", False),
    ("[!a-c]x", "dx", True),
    ("[]a]", "]", True),
    ("[!]a]", "]", False),
    ("[!]a]", "b", True),
    ("[a-]", "-", True),
    ("[-a]", "-", True),
    ("a[bc", "a[bc", True),
    ("a[bc", "ab", False),
    ("[a\\]]", "]", True),
    ("a[!b]c", "a/c", False),
    # escapes
    ("\\*", "*", True),
    ("\\*", "a", False),
    ("a\\?", "a?", True),
    ("a\\?", "ab", False),
    ("a\\", "a\\", True),
    # double star
    ("a/**/b", "a/b", True),
    ("a/**/b", "a/x/b", True),
    ("a/**/b", "a/x/y/b", True),
    ("a/**/b", "a/x/y/c", False),
    ("a/**", "a", True),
    ("a/**", "a/b/c", True),
    ("a/**", "b", False),
    ("**/a", "a", True),
    ("**/a", "x/y/a", True),
    ("**/a", "x/y/ab", False),
    ("**", "a/b/c", True),
    ("**/*.py", "main.py", True),
    ("**/*.py", "a/b/main.py", True),
    ("a**b", "axxb", True),
    ("a**b", "a/b", False),
    ("a/**/**/b", "a/b", True),
    ("**/a/**/b/**", "x/a/y/z/b", True),
    # hidden files
    ("*", ".git", False),
    (".*", ".git", True),
    ("*.txt", ".txt", False),
    ("?git", ".git", False),
    ("[.]git", ".git", False),
    ("\\.git", ".git", True),
    ("a/*", "a/.hidden", False),
    ("a*", "a.b", True),
    ("**/c", "a/.b/c", False),
    ("a/**", "a/.b", False),
    ("**/.b/c", "a/.b/c", True),
    ("a/.*/c", "a/.b/c", True),
    # braces
    ("{a,b}", "a", True),
    ("{a,b}", "c", False),
    ("x{a,b}y", "xby", True),
    ("a{,b}", "a", True),
    ("a{,b}", "ab", True),
    ("{a,b{c,d}}", "bd", True),
    ("{a,b{c,d}}", "b", False),
    ("*.{py,txt}", "a.txt", True),
    ("*.{py,txt}", "a.md", False),
    ("{a/b,c}/d", "a/b/d", True),
    ("{a/b,c}/d", "c/d", True),
    ("{a,**}/b", "x/y/b", True),
    ("{a}", "a", False),
    ("{a}", "{a}", True),
    ("{a,b", "{a,b", True),
    ("{a,b", "a", False),
    ("a\\{b,c\\}", "a{b,c}", True),
    ("{a\\,b,c}", "a,b", True),
    ("{a,b}{c,d}", "bc", True),
    ("{*.py,src/**}", "src/a/b", True),
    ("{a,b}/{c}", "a/{c}", True),
]


@pytest.mark.parametrize(
    "pattern,path,expected", CASES, ids=[f"{p!r} vs {s!r}" for p, s, _ in CASES]
)
def test_match(pattern, path, expected):
    assert match(pattern, path) is expected
