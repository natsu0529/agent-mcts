@pytest.mark.parametrize("start,duration,expected", CASES)
def test_add(start, duration, expected):
    if expected == ERR:
        with pytest.raises(ValueError):
            add_duration(start, duration)
    else:
        assert add_duration(start, duration) == expected


@pytest.mark.parametrize("duration", INVALID)
def test_invalid(duration):
    with pytest.raises(ValueError):
        add_duration(D(2025, 3, 10), duration)
