ERRORS = ["a\nb", "a\rb", "\n"]

HEADER = '''# ruff: noqa: E501
"""Hidden tests for mdinline.render. Generated by gen_hidden.py; do not edit."""

from pathlib import Path

import pytest
from mdinline import render

'''

FOOTER = """

@pytest.mark.parametrize(("text", "html"), CASES)
def test_render(text, html):
    assert render(text) == html


@pytest.mark.parametrize("text", ERRORS)
def test_newline_is_an_error(text):
    with pytest.raises(ValueError):
        render(text)


def test_standard_library_only():
    import mdinline

    assert render("*a*") == "<em>a</em>"
    source = Path(mdinline.__file__).read_text(encoding="utf-8")
    assert "markdown_it" not in source and "import markdown" not in source
"""


def main() -> None:
    md = MarkdownIt("zero").enable(["escape", "backticks", "emphasis"])
    seen: set[str] = set()
    rows: list[tuple[str, str]] = []
    for text in CASES:
        if text in seen:
            raise SystemExit(f"duplicate case {text!r}")
        seen.add(text)
        html = md.renderInline(text)
        mine = reference.render(text)
        if mine != html:
            raise SystemExit(f"reference disagrees on {text!r}: {mine!r} != {html!r}")
        rows.append((text, html))
    for text in ERRORS:
        try:
            reference.render(text)
        except ValueError:
            continue
        raise SystemExit(f"reference accepts {text!r}")
    body = "CASES = [\n" + "".join(f"    ({t!r}, {h!r}),\n" for t, h in rows) + "]\n\n"
    body += "ERRORS = [" + ", ".join(repr(t) for t in ERRORS) + "]\n"
    out = Path(__file__).resolve().parent / "hidden" / "test_hidden_mdinline.py"
    out.write_text(HEADER + body + FOOTER, encoding="utf-8")
    print(f"{len(rows)} cases, {len(ERRORS)} errors -> {out}")


if __name__ == "__main__":
    main()
